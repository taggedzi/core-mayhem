def escape_ts(s):
    return s.replace("'", "\\'")


def ts_list(items, indent='      '):
    lines = [f"{indent}'{escape_ts(i)}'," for i in items]
    return '[\n' + '\n'.join(lines) + '\n    ]'


def build_lexicon(cats, extra_lines=''):
    """Build a  lexicon: { ... },  block."""
    parts = ['  lexicon: {']
    for key, items in cats.items():
        parts.append(f'    {key}: [')
        for item in items:
            parts.append(f"      '{escape_ts(item)}',")
        parts.append('    ],')
    if extra_lines:
        parts.append(extra_lines.rstrip())
    parts.append('  },\n')
    return '\n'.join(parts)


def replace_lexicon(src, persona_name, new_lex_block):
    """Find persona's lexicon block and replace it."""
    marker = f'export const {persona_name}: Personality = {{'
    persona_start = src.index(marker)
    lex_marker = '  lexicon: {'
    lex_start = src.index(lex_marker, persona_start)
    # Count braces to find closing }
    pos = lex_start + len(lex_marker)
    depth = 1
    while depth > 0 and pos < len(src):
        if src[pos] == '{':
            depth += 1
        elif src[pos] == '}':
            depth -= 1
        pos += 1
    # pos is just after closing }
    lex_end = pos
    if lex_end < len(src) and src[lex_end] == ',':
        lex_end += 1
    if lex_end < len(src) and src[lex_end] == '\n':
        lex_end += 1
    return src[:lex_start] + new_lex_block + src[lex_end:]


